# existing_parent PATH: PATH or its nearest existing ancestor.
existing_parent() { local p="$1"; while [ ! -e "$p" ] && [ "$p" != / ]; do p="$(dirname "$p")"; done; printf '%s' "$p"; }
# same_disk A B: true when A and B (or their nearest existing ancestors) are on one file system.
same_disk() {
  local a b
  a="$(df -P "$(existing_parent "$1")" 2>/dev/null | awk 'NR==2{print $1}')"
  b="$(df -P "$(existing_parent "$2")" 2>/dev/null | awk 'NR==2{print $1}')"
  [ -n "$a" ] && [ "$a" = "$b" ]
}

interactive_config() {
  [ -t 0 ] || die "no terminal: use --non-interactive --config FILE (format: bootstrap/config.example.yaml)"
  _out ""
  _out "InHouseCloud: a few questions. Enter keeps the default."
  _out ""
  ask A_DIR "Install directory" "${INSTALL_DIR:-$DEFAULT_INSTALL_DIR}"
  ask A_INGRESS "Ingress: local (this machine only), private (tailnet) or public" "local"
  case "$A_INGRESS" in
    local)   ask A_DOMAIN "Base domain" "cloud.localhost"; ask A_TLS "TLS: off or internal" "off"; ask A_TUNNEL "Tunnel provider" "none" ;;
    private) ask A_DOMAIN "Private base domain (split DNS over Tailscale)" "apps.internal"; ask A_TLS "TLS: internal" "internal"; ask A_TUNNEL "Tunnel provider" "tailscale" ;;
    public)  ask A_DOMAIN "Public base domain" "cloud.example.com"; ask A_TLS "TLS: edge (Cloudflare) or acme (Let's Encrypt)" "acme"; ask A_TUNNEL "Tunnel provider: none or cloudflared" "none" ;;
    *) die "ingress must be local, private or public" ;;
  esac
  ask A_EMAIL "Admin email (Authentik, Gitea and proxy admin)" "admin@example.com"
  ask A_ORG "Gitea organization" "company"
  ask A_BACKUP "Backup destination (a path on another disk or mount)" "${IHC_BACKUP_DESTINATION:-${A_DIR%/}/backups}"
  case "$A_BACKUP" in /*) ;; *) die "the backup destination must be an absolute path" ;; esac
  same_disk "$A_BACKUP" "$(dirname "$A_DIR")" && warn "that is the same disk as the installation: a dead disk takes both. Fine for a try; for real use point it at another disk (docs/backup.md)"
  A_STORAGE=$(ask_yn "Enable object storage (S3-compatible, for apps that store files)?" n)
  A_OPS=$(ask_yn "Enable the ops tools (Portainer, Glances, web terminal, file browser)? Admins only, through the SSO" y)
  A_WETTY_KEY=false
  if [ "$A_OPS" = true ]; then
    A_WETTY_KEY=$(ask_yn "Let the web terminal sign in as $(id -un): add its dedicated key to ~/.ssh/authorized_keys?" y)
  fi
  A_AGENT=$(ask_yn "Enable the operator agent (needs an LLM API key and a chat channel)?" n)
  A_SCHEME=https; [ "$A_TLS" = off ] && A_SCHEME=http
  INSTALL_DIR="$A_DIR"
}

resolve_config() {
  if [ -n "$CONFIG_ARG" ]; then
    [ -f "$CONFIG_ARG" ] || die "config file not found: $CONFIG_ARG"
    [ -z "$INSTALL_DIR" ] && INSTALL_DIR="$($PY "$IHC_LIB/config.py" "$CONFIG_ARG" get install.directory "$DEFAULT_INSTALL_DIR")"
    SOURCE_CONFIG="$CONFIG_ARG"
  elif [ -f "${INSTALL_DIR:-$DEFAULT_INSTALL_DIR}/config.yaml" ]; then
    [ -z "$INSTALL_DIR" ] && INSTALL_DIR="$DEFAULT_INSTALL_DIR"
    SOURCE_CONFIG="$INSTALL_DIR/config.yaml"
  elif [ "$NON_INTERACTIVE" = true ]; then
    die "--non-interactive needs --config FILE (none found at ${INSTALL_DIR:-$DEFAULT_INSTALL_DIR}/config.yaml)"
  else
    interactive_config
    SOURCE_CONFIG="$(mktemp "${TMPDIR:-/tmp}/ihc-config.XXXXXX")"
    write_answers_config "$SOURCE_CONFIG"
  fi
  INSTALL_DIR="${INSTALL_DIR%/}"
  CONFIG_FILE="$INSTALL_DIR/config.yaml"
  STATE_FILE="$INSTALL_DIR/state.json"
  ENV_FILE="$INSTALL_DIR/.env"
  CONFIG_SHA="$($PY "$IHC_LIB/config.py" "$SOURCE_CONFIG" sha)"
  eval "$($PY "$IHC_LIB/config.py" "$SOURCE_CONFIG" flatten)"
}

# Derived values: everything the compose file and the scripts need, from the config.
derive() {
  INGRESS="${CFG_ingress__mode:-local}"
  BASE_DOMAIN="${CFG_ingress__base_domain:-cloud.localhost}"
  TLS_MODE="${CFG_ingress__tls_mode:-off}"
  TUNNEL_PROVIDER="${CFG_ingress__tunnel_provider:-none}"
  SCHEME=https; [ "$TLS_MODE" = off ] && SCHEME=http
  PORTAL_HOST="${CFG_portal__domain:-portal.$BASE_DOMAIN}"
  PUBLIC_BASE_URL="${CFG_ingress__public_base_url:-$SCHEME://$PORTAL_HOST}"
  PORTAL_BASE_URL="$PUBLIC_BASE_URL"
  AUTHENTIK_HOST="auth.$BASE_DOMAIN"
  AUTHENTIK_BASE_URL="$SCHEME://$AUTHENTIK_HOST"
  GITEA_BASE_URL="${CFG_gitea__base_url:-$SCHEME://git.$BASE_DOMAIN}"
  GITEA_HOST="${GITEA_BASE_URL#*://}"; GITEA_HOST="${GITEA_HOST%%/*}"
  # private: the tailnet reaches the proxy through the Tailscale node, so nothing is
  # published beyond loopback (smoke test 21).
  BIND_ADDRESS=0.0.0.0; case "$INGRESS" in local|private) BIND_ADDRESS=127.0.0.1 ;; esac
  PROFILES=""
  # The provider value of configs written before the switch to Garage still turns storage on.
  case "${CFG_storage__provider:-none}" in garage|minio) STORAGE_PROVIDER_ON=true ;; *) STORAGE_PROVIDER_ON=false ;; esac
  [ "${CFG_install__profile__storage:-false}" = true ] || [ "$STORAGE_PROVIDER_ON" = true ] && PROFILES="$PROFILES,storage"
  # The Gitea Actions runners are core (push to main deploys): no ci profile any more.
  CI_IGNORED=""
  [ -n "${CFG_install__profile__ci:-}" ] && CI_IGNORED="install.profile.ci"
  [ -n "${CFG_ci__gitea_runner__enabled:-}" ] && CI_IGNORED="${CI_IGNORED:+$CI_IGNORED and }ci.gitea_runner.enabled"
  [ "${CFG_install__profile__ops:-false}" = true ] || [ "${CFG_ops__portainer:-false}" = true ] || [ "${CFG_ops__glances:-false}" = true ] && PROFILES="$PROFILES,ops"
  case "$TUNNEL_PROVIDER" in cloudflared|tailscale) PROFILES="$PROFILES,$TUNNEL_PROVIDER" ;; esac
  BACKUP_ENABLED="${CFG_backup__enabled:-true}"
  [ "$BACKUP_ENABLED" = true ] && PROFILES="$PROFILES,backup"
  [ "${CFG_install__profile__agent:-false}" = true ] || [ "${CFG_ops__agent__enabled:-false}" = true ] && PROFILES="$PROFILES,agent"
  PROFILES="${PROFILES#,}"
  BACKUP_DEST_ENV="${CFG_backup__destination_env:-${CFG_backup__remote__destination_env:-IHC_BACKUP_DESTINATION}}"
  BACKUP_KEY_ENV="${CFG_backup__encryption_key_env:-${CFG_backup__remote__encryption_key_env:-IHC_BACKUP_ENCRYPTION_KEY}}"
  # Destination: the environment variable named in the config, else backup.destination,
  # else what .env already has, else <install-dir>/backups.
  eval "BACKUP_DEST=\${$BACKUP_DEST_ENV:-}"
  [ -z "$BACKUP_DEST" ] && BACKUP_DEST="${CFG_backup__destination:-}"
  [ -z "$BACKUP_DEST" ] && [ -f "$INSTALL_DIR/.env" ] && BACKUP_DEST="$($PY "$IHC_LIB/envfile.py" get "$INSTALL_DIR/.env" BACKUP_DESTINATION)"
  [ -z "$BACKUP_DEST" ] && BACKUP_DEST="$INSTALL_DIR/backups"
  BACKUP_DEST="${BACKUP_DEST%/}"
  ADMIN_EMAIL="${CFG_admin__email:-admin@example.com}"
  derive_ops
  derive_agent
  RESUME_PREFIX="$SELF --apply --install-dir $INSTALL_DIR"
}

has_profile() { case ",$PROFILES," in *",$1,"*) return 0 ;; *) return 1 ;; esac; }

# ------------------------------------------------------------------- ops tools
# The ops profile: Portainer, Glances, Wetty (web terminal on the host, over ssh) and
# FileBrowser (app data and backup reports). All four are admin access to the machine,
# behind forward auth bound to ihc-admins (docs/security.md).

# detect_sshd [PORT...]: the first port on 127.0.0.1 that answers with an SSH banner,
# trying PORT, then the Port lines of sshd_config, then 22.
detect_sshd() {
  $PY -c '
import glob, re, socket, sys
ports = [p for p in sys.argv[1:] if p]
for f in ["/etc/ssh/sshd_config"] + sorted(glob.glob("/etc/ssh/sshd_config.d/*.conf")):
    try:
        for line in open(f):
            m = re.match(r"\s*Port\s+(\d+)", line, re.I)
            if m: ports.append(m.group(1))
    except OSError:
        pass
ports.append("22")
seen = set()
for p in ports:
    if p in seen: continue
    seen.add(p)
    try:
        s = socket.create_connection(("127.0.0.1", int(p)), timeout=3)
        s.settimeout(3)
        banner = s.recv(64)
        s.close()
        if banner.startswith(b"SSH-"):
            print(p); break
    except (OSError, ValueError):
        pass
' "$@"
}

# expand_ops_path VALUE: ${install_dir} and ${backup_destination} in an ops.filebrowser path.
expand_ops_path() {
  $PY -c 'import sys
v = sys.argv[1].replace("${install_dir}", sys.argv[2]).replace("${backup_destination}", sys.argv[3])
print(v.rstrip("/") or "/")' "$1" "$INSTALL_DIR" "$BACKUP_DEST"
}

derive_ops() {
  OPS_ON=false
  if has_profile ops; then OPS_ON=true; fi
  WETTY_KEY_DIR="$INSTALL_DIR/local/wetty"
  WETTY_INSTALL_KEY="${CFG_ops__wetty__install_key:-false}"
  WETTY_ENABLED="${CFG_ops__wetty__enabled:-true}"
  local d_app='${install_dir}/app-data' d_rep='${backup_destination}/reports'
  FB_APP_DATA="$(expand_ops_path "${CFG_ops__filebrowser__paths__app_data:-$d_app}")"
  FB_REPORTS="$(expand_ops_path "${CFG_ops__filebrowser__paths__backup_reports:-$d_rep}")"
  SSHD_PORT=""
  if [ "$OPS_ON" = true ] && [ "$WETTY_ENABLED" = true ]; then
    SSHD_PORT="$(detect_sshd "${CFG_ops__wetty__ssh_port:-}" 2>/dev/null || true)"
  fi
  WETTY_ON=false
  if [ -n "$SSHD_PORT" ]; then WETTY_ON=true; fi
}
