run_stage() {
  local name="$1" status sha
  status="$(state stage "$name" status)"
  sha="$(state stage "$name" get config_sha256 | tr -d '"')"
  if [ "$status" = completed ] && [ "$sha" = "$CONFIG_SHA" ]; then
    ok "$name: already completed"
    return 0
  fi
  [ "$status" = completed ] && log "$name: completed with another config; re-running (every action probes before it creates)"
  step "$name"
  state stage "$name" start --config-sha "$CONFIG_SHA" --resume "$RESUME_PREFIX --from $name"
  if "stage_$name"; then
    state stage "$name" complete
  else
    state stage "$name" fail --error-code "E_$(printf '%s' "$name" | tr 'a-z' 'A-Z')"
    [ "${DRY_RUN:-false}" = true ] && die "the plan stopped at $name; nothing was created. Fix the cause above and plan again."
    fail "stage $name failed. Fix the cause and resume with:"
    fail "  $RESUME_PREFIX --from $name"
    [ "$JSON_OUTPUT" = true ] && state status --json
    exit 1
  fi
}

