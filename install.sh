# ensure_database ROLE DB PASSWORD: role LOGIN NOSUPERUSER owning its database, no
# public connect. The password goes in on stdin, never on a command line.
ensure_database() {
  local role="$1" db="$2" pw="$3"
  dc exec -T postgres psql -v ON_ERROR_STOP=1 -U "$(env_get POSTGRES_USER)" -d postgres -q <<SQL || return 1
DO \$\$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '$role') THEN
    CREATE ROLE "$role" LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$pw';
  ELSE
    ALTER ROLE "$role" WITH LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE PASSWORD '$pw';
  END IF;
END \$\$;
SELECT 'CREATE DATABASE "$db" OWNER "$role"' WHERE NOT EXISTS (SELECT 1 FROM pg_database WHERE datname = '$db') \gexec
REVOKE CONNECT ON DATABASE "$db" FROM PUBLIC;
GRANT CONNECT ON DATABASE "$db" TO "$role";
SQL
  ok "database $db and role $role present (LOGIN NOSUPERUSER, no public connect)"
  state stage shared_data set resources "[\"postgres:role:$role\",\"postgres:database:$db\"]"
}

