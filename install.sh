#!/usr/bin/env bash
# InHouseCloud: one-command installer (docs/install-design.md).
#
#   ./install.sh                                  ask the questions, show the plan, apply
#   ./install.sh --plan [--config FILE]           print what would happen, change nothing
#   ./install.sh --apply [--config FILE]          apply without the confirmation prompt
#   ./install.sh --non-interactive --config FILE  for agents and CI: no prompts at all
#   ./install.sh --apply --from STAGE             resume (re-run) from STAGE
#   ./install.sh status [--verbose] [--json]      short state: URLs, health, backup age, apps
#   ./install.sh handoff                          the day-zero steps again
#   ./install.sh stop | start                     stop the cloud and its apps (data kept), start again
#   ./install.sh remove [--images] [--dir]        remove a test install (docs/cleanup.md); asks
#                                                 for the project name, or --confirm NAME
#
# Options: --install-dir DIR  --json  --yes
# Every stage records itself in <install-dir>/state.json (bootstrap/state.example.json).
# Re-running on an installed box changes nothing; after a failure it resumes at the
# failed stage. Secrets are generated into <install-dir>/.env (0600) and never printed.
# Requires bash 3.2+, Docker with Compose v2, python3 and curl. No root beyond Docker.
set -eu

SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
IHC_ROOT="$(cd "$(dirname "$0")" && pwd)"
# shellcheck source=scripts/lib/common.sh
. "$IHC_ROOT/scripts/lib/common.sh"
# shellcheck source=scripts/lib/garage.sh
. "$IHC_ROOT/scripts/lib/garage.sh"
# shellcheck source=scripts/lib/tls.sh
. "$IHC_ROOT/scripts/lib/tls.sh"

DEFAULT_INSTALL_DIR="/opt/inhousecloud"
MODE=""              # plan | apply
NON_INTERACTIVE=false
CONFIG_ARG=""
FROM_STAGE=""
INSTALL_DIR="${IHC_INSTALL_DIR:-}"
ASSUME_YES=false
SUBCOMMAND=""
VERBOSE=false; CONFIRM_ARG=""; REMOVE_IMAGES=false; REMOVE_DIR=false

usage() { sed -n '2,19p' "$SELF" | sed 's/^# \{0,1\}//'; }

while [ $# -gt 0 ]; do
  case "$1" in
    --plan) MODE=plan ;;
    --apply) MODE=apply ;;
    --non-interactive) NON_INTERACTIVE=true; [ -z "$MODE" ] && MODE=apply ;;
    --config) CONFIG_ARG="$2"; shift ;;
    --config=*) CONFIG_ARG="${1#*=}" ;;
    --from) FROM_STAGE="$2"; shift ;;
    --from=*) FROM_STAGE="${1#*=}" ;;
    --install-dir) INSTALL_DIR="$2"; shift ;;
    --install-dir=*) INSTALL_DIR="${1#*=}" ;;
    --json) JSON_OUTPUT=true ;;
    --yes|-y) ASSUME_YES=true ;;
    status|handoff|stop|start|remove) SUBCOMMAND="$1" ;;
    --verbose|-v) VERBOSE=true ;;
    --confirm) CONFIRM_ARG="$2"; shift ;;
    --confirm=*) CONFIRM_ARG="${1#*=}" ;;
    --images) REMOVE_IMAGES=true ;;
    --dir) REMOVE_DIR=true ;;
    -h|--help) usage; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
  shift
done

# ------------------------------------------------------------ configuration
# Answers come from --config, from <install-dir>/config.yaml on a re-run, or from
# the questions below. The chosen file is copied to <install-dir>/config.yaml.

ask() { # ask VAR "Question" "default"
  local var="$1" q="$2" def="$3" ans
  printf '%s [%s]: ' "$q" "$def" >&2
  read -r ans || ans=""
  [ -z "$ans" ] && ans="$def"
  eval "$var=\"\$ans\""
}
ask_yn() { # ask_yn "Question" default(y|n) -> echoes true|false
  local ans
  printf '%s [%s]: ' "$1" "$2" >&2
  read -r ans || ans=""
  [ -z "$ans" ] && ans="$2"
  case "$ans" in y|Y|yes|YES) echo true ;; *) echo false ;; esac
}

