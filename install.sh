stage_preflight() {
  local errors=0 probe='{}' os docker_v compose_v disk_kb mem_mb port
  os="$(uname -s)"
  case "$os" in Linux|Darwin) ok "OS: $os $(uname -m)" ;; *) warn "untested OS: $os" ;; esac
  for tool in docker python3 curl; do
    have "$tool" && ok "$tool found" || { fail "$tool not found"; errors=$((errors+1)); }
  done
  if have docker; then
    if docker info >/dev/null 2>&1; then
      docker_v="$(docker version --format '{{.Server.Version}}' 2>/dev/null || echo unknown)"; ok "Docker daemon reachable ($docker_v)"
    else
      fail "Docker daemon not reachable: is Docker running, and is $(id -un) in the docker group?"; errors=$((errors+1))
    fi
    if docker compose version >/dev/null 2>&1; then
      compose_v="$(docker compose version --short 2>/dev/null || echo unknown)"; ok "Compose v2 ($compose_v)"
    else
      fail "Docker Compose v2 plugin not found"; errors=$((errors+1))
    fi
  fi
  # Install directory: must exist and be writable, or be creatable without root.
  if [ -d "$INSTALL_DIR" ]; then
    [ -w "$INSTALL_DIR" ] && ok "install dir writable: $INSTALL_DIR" || { fail "install dir not writable: $INSTALL_DIR"; errors=$((errors+1)); }
  elif [ "$DRY_RUN" = true ]; then
    # Planning creates nothing: only check that apply could create it.
    [ -w "$(existing_parent "$INSTALL_DIR")" ] && ok "install dir: $INSTALL_DIR (created on apply)" \
      || { fail "cannot create $INSTALL_DIR. Create it once with: sudo install -d -o $(id -un) -g $(id -gn) $INSTALL_DIR"; errors=$((errors+1)); }
  else
    if mkdir -p "$INSTALL_DIR" 2>/dev/null; then ok "install dir created: $INSTALL_DIR"
    else fail "cannot create $INSTALL_DIR. Create it once with: sudo install -d -o $(id -un) -g $(id -gn) $INSTALL_DIR"; errors=$((errors+1)); fi
  fi
  # Disk (10 GiB free where the install dir lives) and memory (3.5 GiB).
  disk_kb="$(df -Pk "$(existing_parent "$(dirname "$INSTALL_DIR")")" 2>/dev/null | awk 'NR==2{print $4}')"
  [ -n "$disk_kb" ] && { [ "$disk_kb" -ge 10485760 ] && ok "disk free: $((disk_kb/1048576)) GiB" || { fail "disk free: $((disk_kb/1048576)) GiB (need 10)"; errors=$((errors+1)); }; }
  # macOS: Docker Desktop's disk image grows into the host disk (about 5.4 GiB for core and
  # backup) and does not give the space back by itself. A warning, not a stop.
  [ "$os" = Darwin ] && [ -n "$disk_kb" ] && [ "$disk_kb" -ge 10485760 ] && [ "$disk_kb" -lt 15728640 ] \
    && warn "disk free: $((disk_kb/1048576)) GiB on this Mac; 15 to 20 GiB is recommended (the images take about 5.4 GiB in Docker Desktop's disk image, which does not shrink on its own: docs/cleanup.md)"
  if [ "$os" = Linux ]; then mem_mb=$(awk '/MemTotal/{print int($2/1024)}' /proc/meminfo); else mem_mb=$(( $(sysctl -n hw.memsize) / 1048576 )); fi
  [ "$mem_mb" -ge 3500 ] && ok "memory: ${mem_mb} MiB" || { fail "memory: ${mem_mb} MiB (need 3.5 GiB)"; errors=$((errors+1)); }
  # Ports: only on a first install; on a re-run our own containers hold them.
  if [ ! -f "$ENV_FILE" ]; then
    for port in 80 443 81 2222 9000 3000; do
      port_in_use "$port" && { fail "port $port is already in use on 127.0.0.1"; errors=$((errors+1)); } || ok "port $port free"
    done
  else
    ok "existing installation: port check skipped"
  fi
  # Domain
  case "$BASE_DOMAIN" in
    *.*) ok "base domain: $BASE_DOMAIN" ;;
    *) fail "base domain must contain a dot: $BASE_DOMAIN"; errors=$((errors+1)) ;;
  esac
  [ "$INGRESS" = local ] && case "$BASE_DOMAIN" in *.localhost) ;; *) warn "ingress local with a domain outside .localhost: make $BASE_DOMAIN resolve to this machine yourself" ;; esac
  # Ingress matrix (docs/install-design.md)
  case "$INGRESS/$TLS_MODE/$TUNNEL_PROVIDER" in
    local/off/none|local/internal/none|private/internal/tailscale|public/edge/cloudflared|public/acme/none|public/acme/cloudflared)
      ok "ingress $INGRESS, tls $TLS_MODE, tunnel $TUNNEL_PROVIDER" ;;
    *) fail "refused ingress combination: INGRESS=$INGRESS TLS_MODE=$TLS_MODE TUNNEL_PROVIDER=$TUNNEL_PROVIDER (see the matrix in docs/install-design.md)"; errors=$((errors+1)) ;;
  esac
  case "$TUNNEL_PROVIDER" in
    cloudflared) eval "t=\${${CFG_ingress__cloudflared__tunnel_token_env:-IHC_CLOUDFLARED_TUNNEL_TOKEN}:-}"; [ -n "$t" ] && ok "cloudflared tunnel token present in the environment" || { fail "set ${CFG_ingress__cloudflared__tunnel_token_env:-IHC_CLOUDFLARED_TUNNEL_TOKEN} in the environment"; errors=$((errors+1)); } ;;
    tailscale)
      if [ -f "$ENV_FILE" ] && [ "$(ts_backend)" = Running ]; then ok "tailscale: node $(env_get TAILSCALE_HOSTNAME) logged in ($(env_get TAILSCALE_IP)); no auth key needed"
      elif [ -n "${IHC_TAILSCALE_AUTHKEY:-}" ]; then ok "tailscale auth key present in the environment (first login only; never written to .env)"
      elif [ -f "$ENV_FILE" ] && docker volume inspect "$(env_get COMPOSE_PROJECT_NAME)_tailscale-state" >/dev/null 2>&1; then warn "tailscale: no auth key in the environment; the node will try its saved state (volume tailscale-state). If it was removed from the tailnet, export IHC_TAILSCALE_AUTHKEY"
      else fail "set IHC_TAILSCALE_AUTHKEY in the environment: an auth key from the Tailscale admin console (Settings > Keys), used for the first login only"; errors=$((errors+1)); fi
      [ -n "${CFG_ingress__tailscale__private_dns_zone:-}" ] && [ "$CFG_ingress__tailscale__private_dns_zone" != "$BASE_DOMAIN" ] && warn "ingress.tailscale.private_dns_zone ($CFG_ingress__tailscale__private_dns_zone) differs from base_domain: the split DNS zone is base_domain"
      if [ -f "$ENV_FILE" ] && [ -n "$(env_get TAILSCALE_IP)" ] && [ "$(ts_backend)" = Running ]; then
        a="$(ts_resolve "portal.$BASE_DOMAIN")"
        [ "$a" = "$(env_get TAILSCALE_IP)" ] && ok "dns: portal.$BASE_DOMAIN resolves to the tailnet address $a from this box" || warn "dns: portal.$BASE_DOMAIN resolves to '${a:-nothing}' from this box, not $(env_get TAILSCALE_IP); the proxy_ingress stage re-renders it"
      fi ;;
  esac
  [ -n "$CI_IGNORED" ] && warn "config: $CI_IGNORED ignored; the Gitea Actions runners are part of core now (docs/gitops-flow.md)"
  # Backup destination: warned about, not fatal (the backup stage fails on its own).
  if [ "$BACKUP_ENABLED" = true ]; then
    if case "$BACKUP_DEST" in /*) false ;; *) true ;; esac; then
      fail "backup destination must be an absolute path: $BACKUP_DEST ($BACKUP_DEST_ENV)"; errors=$((errors+1))
    elif [ -d "$BACKUP_DEST" ]; then
      [ -w "$BACKUP_DEST" ] && ok "backup destination writable: $BACKUP_DEST" || warn "backup destination not writable by $(id -un): $BACKUP_DEST. Fix with: sudo chown $(id -un) $BACKUP_DEST (or set $BACKUP_DEST_ENV to another path); the backup stage will fail until then"
    elif [ "$DRY_RUN" = true ]; then
      [ -w "$(existing_parent "$BACKUP_DEST")" ] && ok "backup destination: $BACKUP_DEST (created on apply)" || warn "cannot create the backup destination $BACKUP_DEST: create it, writable by $(id -un), or set $BACKUP_DEST_ENV; the backup stage will fail until then"
    elif mkdir -p "$BACKUP_DEST" 2>/dev/null; then ok "backup destination created: $BACKUP_DEST"
    else warn "cannot create the backup destination $BACKUP_DEST: create it, writable by $(id -un), or set $BACKUP_DEST_ENV; the backup stage will fail until then"; fi
    if same_disk "$BACKUP_DEST" "$(dirname "$INSTALL_DIR")"; then
      warn "backup destination is on the same disk as the installation: a dead disk takes both. Set backup.destination (or $BACKUP_DEST_ENV) to another disk or mount (docs/backup.md)"
    fi
    eval "k=\${$BACKUP_KEY_ENV:-}"
    [ -n "$k" ] && ok "backup encryption key present in the environment ($BACKUP_KEY_ENV)" || log "backup encryption key: generated into .env unless $BACKUP_KEY_ENV is set; keep a copy off this box"
  else
    log "backup disabled (backup.enabled: false)"
  fi
  if [ "$OPS_ON" = true ]; then
    if [ "$WETTY_ENABLED" != true ]; then log "ops: web terminal disabled (ops.wetty.enabled: false)"
    elif [ -n "$SSHD_PORT" ]; then ok "ops: sshd answers on port $SSHD_PORT: the web terminal signs in as $(id -un)"
    else warn "ops: no sshd answers on this host (tried ${CFG_ops__wetty__ssh_port:+$CFG_ops__wetty__ssh_port, }the sshd_config Port lines and 22): the ops tools come up without the web terminal. Install and start openssh-server, then re-run install.sh"; fi
    if $PY "$IHC_LIB/opspaths.py" check "$INSTALL_DIR" "$BACKUP_DEST" "$FB_APP_DATA" "$FB_REPORTS"; then
      ok "ops: file browser paths $FB_APP_DATA and $FB_REPORTS (read only)"
    else
      fail "ops: refused ops.filebrowser.paths (see above)"; errors=$((errors+1))
    fi
  fi
  [ "$AGENT_ON" = true ] && agent_preflight
  if [ "$TLS_MODE" = internal ]; then
    have openssl && ok "tls internal: openssl found; the installer makes a CA in $INSTALL_DIR/local/ca and a certificate for *.$BASE_DOMAIN" \
      || ok "tls internal: no openssl on the host; the CA is made with the proxy image's openssl"
  fi
  probe="$(jsonq build os="$os" docker="${docker_v:-}" compose="${compose_v:-}" memory_mb="${mem_mb:-}" disk_free_gib="$((${disk_kb:-0}/1048576))" ingress="$INGRESS/$TLS_MODE/$TUNNEL_PROVIDER" backup_destination="$BACKUP_DEST" errors:="$errors")"
  state stage preflight set probe "$probe"
  [ "$errors" -eq 0 ] || return 1
}

